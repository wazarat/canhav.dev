#!/usr/bin/env node
/**
 * Workflow template module generator (M144). Reads the two GitHub Actions
 * templates under .github-templates and writes lib/workflows/templates.ts,
 * a string module the download route serves with the project's values
 * filled in, so the route reads no file at request time. Run with
 *
 *   npm run gen:workflows          write the module
 *   npm run check:workflows        fail when the module drifts from the YAML
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(new URL(".", import.meta.url).pathname, "..");
const SRC = path.join(ROOT, ".github-templates");
const OUT = path.join(ROOT, "lib/workflows/templates.ts");
const CHECK = process.argv.includes("--check");

const FILES = { sync: "canhav-sync.yml", checks: "canhav-checks.yml" };

const entries = Object.entries(FILES).map(([name, file]) => {
  const text = fs.readFileSync(path.join(SRC, file), "utf8");
  if (!text.includes("${{ vars.CANHAV_CHAIN_ID }}")) throw new Error(`${file} has no CANHAV_CHAIN_ID variable to fill`);
  if (!text.includes("${{ vars.CANHAV_URL || 'https://www.canhav.com' }}")) throw new Error(`${file} has no CANHAV_URL variable to fill`);
  return [name, text];
});

const body = [
  "// Generated by scripts/gen-workflow-templates.mjs from .github-templates. Do not edit; run npm run gen:workflows.",
  "",
  "/** The GitHub Actions templates as strings (M144), keyed by the workflow name the download route takes. */",
  "export const WORKFLOW_TEMPLATES = {",
  // The YAML carries colons by nature; copy-ok keeps scripts/check-copy.mjs off the generated lines.
  ...entries.map(([name, text]) => `  ${name}: ${JSON.stringify(text)}, // copy-ok, generated YAML`),
  "} as const;",
  "",
  "export type WorkflowName = keyof typeof WORKFLOW_TEMPLATES;",
  "",
  "export function isWorkflowName(value: unknown): value is WorkflowName {",
  '  return typeof value === "string" && value in WORKFLOW_TEMPLATES;',
  "}",
  "",
].join("\n");

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error("lib/workflows/templates.ts drifts from .github-templates. Run npm run gen:workflows.");
    process.exit(1);
  }
  console.log("lib/workflows/templates.ts matches .github-templates.");
} else {
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${entries.length} templates).`);
}
